void gfx_init(void *buffer, u32 width, u32 height) {
    s_fb.pixels = (u32 *)buffer;
    s_fb.width = width;
    s_fb.height = height;
    s_fb.stride = width;
}

Framebuffer *gfx_get_framebuffer(void) {
    return &s_fb;
}

void gfx_clear(u32 color) {
    if (!s_fb.pixels) return;
    u32 total = s_fb.width * s_fb.height;
    for (u32 i = 0; i < total; i++) {
        s_fb.pixels[i] = color;
    }
}

void gfx_draw_pixel(u32 x, u32 y, u32 color) {
    if (!s_fb.pixels || x >= s_fb.width || y >= s_fb.height) return;
    s_fb.pixels[y * s_fb.stride + x] = color;
}

void gfx_draw_rect(u32 x, u32 y, u32 w, u32 h, u32 color) {
    if (!s_fb.pixels) return;
    for (u32 py = y; py < y + h && py < s_fb.height; py++) {
        for (u32 px = x; px < x + w && px < s_fb.width; px++) {
            s_fb.pixels[py * s_fb.stride + px] = color;
        }
    }
}

void gfx_draw_char(u32 x, u32 y, char c, u32 fg, u32 bg) {
    if (!s_fb.pixels || c < 32 || c > 126) return;
    const u8 *glyph = font8x8_basic[c - 32];
    for (u32 row = 0; row < 8; row++) {
        u8 bits = glyph[row];
        for (u32 col = 0; col < 8; col++) {
            bool on = (bits & (1 << col)) != 0;
            if (on) {
                gfx_draw_pixel(x + col, y + row, fg);
            } else if ((bg >> 24) != 0) { // Se não for transparente
                gfx_draw_pixel(x + col, y + row, bg);
            }
        }
    }
}

void gfx_draw_text(u32 x, u32 y, const char *str, u32 fg, u32 bg) {
    if (!str) return;
    u32 cur_x = x;
    u32 cur_y = y;
    while (*str) {
        if (*str == '\n') {
            cur_x = x;
            cur_y += 10;
        } else {
            gfx_draw_char(cur_x, cur_y, *str, fg, bg);
            cur_x += 8;
        }
        str++;
    }
}
